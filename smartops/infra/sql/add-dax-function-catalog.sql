/* ============================================================================
   TWise engine support. The Chart/Report Builder evaluate a subset of DAX
   (core/utils/dax-evaluator.util.ts, DAX_FUNCTION_MIN_ARGS). Smart compose
   only suggests what that engine runs; everything else stays in the catalog
   with IsEnabled = 0, so turning more on later is an UPDATE.
   ============================================================================ */
UPDATE dbo.DaxFunction
SET IsEnabled = CASE WHEN FunctionName IN (
    N'SUM', N'PRODUCT', N'AVERAGE', N'MIN', N'MAX', N'COUNT', N'DISTINCTCOUNT', N'MEDIAN', N'COUNTROWS',
    N'BLANK', N'COALESCE', N'DIVIDE', N'IF', N'SWITCH', N'AND', N'OR', N'NOT', N'IFERROR', N'ROUND', N'ABS',
    N'TRUE', N'FALSE',
    N'LEN', N'LEFT', N'RIGHT', N'MID', N'UPPER', N'LOWER', N'TRIM', N'CONCATENATE', N'SUBSTITUTE',
    N'FIND', N'SEARCH', N'VALUE', N'EXACT',
    N'TODAY', N'NOW', N'DATE', N'DATEVALUE', N'YEAR', N'MONTH', N'DAY', N'QUARTER', N'WEEKDAY', N'DATEDIFF', N'EOMONTH'
) THEN 1 ELSE 0 END;
GO

-- The engine needs the DATEDIFF unit in quotes ("DAY", "WEEK", "MONTH", ...).
UPDATE dbo.DaxFunction
SET Syntax = N'DATEDIFF(Date1, Date2, "Interval")',
    InsertSnippet = N'DATEDIFF(${1:Date1}, ${2:Date2}, "${3:DAY}")$0'
WHERE FunctionName = N'DATEDIFF';
GO

