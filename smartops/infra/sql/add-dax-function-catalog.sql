/* Prefix suggestions for smart compose.
   Ranking: exact match, then prefix match on full name, then prefix on a dotted segment (e.g. 'DIST' -> NORM.DIST),
   then usage, then name. Pass @ReturnType to favour functions that fit the caret position. */
CREATE PROCEDURE dbo.usp_DaxSuggest
    @Prefix      NVARCHAR(128),
    @ReturnType  NVARCHAR(20) = NULL,
    @Top         INT = 15
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @p NVARCHAR(130) = REPLACE(REPLACE(REPLACE(UPPER(LTRIM(RTRIM(@Prefix))), N'[', N'[[]'), N'%', N'[%]'), N'_', N'[_]');

    SELECT TOP (@Top)
           f.FunctionName, f.Category, f.Syntax, f.ReturnType, f.Description,
           f.InsertSnippet, f.MinArgs, f.MaxArgs, f.IsNotRecommended, f.IsDeprecated, f.DocUrl
    FROM dbo.DaxFunction AS f
    WHERE f.IsEnabled = 1
      AND (f.FunctionName LIKE @p + N'%' OR f.FunctionName LIKE N'%.' + @p + N'%')
    ORDER BY
      CASE WHEN f.FunctionName = UPPER(@Prefix) THEN 0
           WHEN f.FunctionName LIKE @p + N'%'  THEN 1 ELSE 2 END,
      CASE WHEN @ReturnType IS NULL OR f.ReturnType = @ReturnType OR f.ReturnType = N'Variant' THEN 0 ELSE 1 END,
      f.IsDeprecated, f.IsNotRecommended,
      f.UsageCount DESC,
      LEN(f.FunctionName), f.FunctionName;
END;
GO

